def emoji_vehiculo(tipo):
    """Emoji del tipo; los tipos escritos a mano se reconocen por palabras clave."""
    if tipo in EMOJI_VEHICULO:
        return EMOJI_VEHICULO[tipo]
    texto = tipo.casefold()
    for clave, emoji in (("moto", "🏍️"), ("taxi", "🚕"), ("carro", "🚗"), ("auto", "🚗"),
                         ("micro", "🚐"), ("mini", "🚐"), ("van", "🚐")):
        if clave in texto:
            return emoji
    return "🚌"

